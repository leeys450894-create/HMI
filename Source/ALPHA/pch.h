class CCriticalSectionSync
{
	CCriticalSection* m_pSyncObject;

public:
	CCriticalSectionSync(CCriticalSection* pSyncObject, BOOL bInitialLock = FALSE)
	{
		m_pSyncObject = pSyncObject;

		if (bInitialLock)
		{
			m_pSyncObject->Lock();
		}
	}
	~CCriticalSectionSync(void)
	{
		m_pSyncObject->Unlock();
	}
};

